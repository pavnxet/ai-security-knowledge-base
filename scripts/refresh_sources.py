#!/usr/bin/env python3
"""Re-resolve default-branch commit SHA, license, archived, stars for every source.

Uses the GitHub REST API (stdlib only). In CI pass --token "$GITHUB_TOKEN".
Writes sources.yaml in place; never touches human-edited cards.
"""
import os, sys, json, time, argparse, urllib.request, urllib.error, yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def api(url, token):
    req = urllib.request.Request(url, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "secure-kb-refresh",
        **({"Authorization": f"Bearer {token}"} if token else {}),
    })
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--token", default=os.environ.get("GITHUB_TOKEN"))
    a = ap.parse_args()
    doc = yaml.safe_load(open(os.path.join(ROOT, "sources.yaml")))
    changed = []
    for s in doc["sources"]:
        repo = s["repo"]
        try:
            meta = api(f"https://api.github.com/repos/{repo}", a.token)
            br = meta.get("default_branch")
            commit = api(f"https://api.github.com/repos/{repo}/commits/{br}", a.token).get("sha")
            new = {"license": (meta.get("license") or {}).get("spdx_id") or "NOASSERTION",
                   "stars": meta.get("stargazers_count"), "archived": bool(meta.get("archived")),
                   "last_pushed": (meta.get("pushed_at") or "")[:10], "default_branch": br,
                   "commit": commit, "last_verified": time.strftime("%Y-%m-%d")}
            for k, v in new.items():
                if s.get(k) != v:
                    changed.append((repo, k, s.get(k), v))
                    s[k] = v
        except urllib.error.HTTPError as e:
            print(f"WARN {repo}: HTTP {e.code}", file=sys.stderr)
        except Exception as e:
            print(f"WARN {repo}: {e}", file=sys.stderr)
        time.sleep(0.3)
    with open(os.path.join(ROOT, "sources.yaml"), "w") as f:
        f.write("# secure-kb source registry - regenerated by scripts/refresh_sources.py\n")
        yaml.safe_dump(doc, f, sort_keys=False, allow_unicode=True, width=120)
    print(f"refresh complete; {len(changed)} field changes")
    for c in changed[:40]:
        print("  ", c)

if __name__ == "__main__":
    main()
