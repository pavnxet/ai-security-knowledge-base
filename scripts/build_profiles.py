#!/usr/bin/env python3
"""Build profiles/<platform>.yaml + playbooks/ from the check cards."""
import os, yaml, glob, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_cards():
    cards = []
    for p in glob.glob(os.path.join(ROOT, "checks", "**", "*.yaml"), recursive=True):
        with open(p) as f:
            cards.append(yaml.safe_load(f))
    return cards

# fingerprint file globs / signal regexes -> platform
FINGERPRINTS = {
    "web":        {"files": ["package.json", "requirements.txt", "pyproject.toml", "composer.json", "Gemfile", "go.mod", "pom.xml", "*.html"],
                   "signals": ["express", "next", "django", "flask", "rails", "laravel", "spring"]},
    "api":        {"files": ["openapi.yaml", "openapi.json", "swagger.json", "**/routes/**", "**/api/**"],
                   "signals": ["/api/", "rest", "graphql", "fastapi"]},
    "mobile":     {"files": ["AndroidManifest.xml", "Info.plist", "Podfile", "*.xcodeproj", "pubspec.yaml"],
                   "signals": ["react-native", "flutter", "kotlin", "swift"]},
    "android":    {"files": ["AndroidManifest.xml", "build.gradle", "build.gradle.kts", "*.apk"],
                   "signals": ["com.android", "androidx"]},
    "ios":        {"files": ["Info.plist", "Podfile", "*.xcodeproj", "*.xcworkspace"],
                   "signals": ["UIKit", "SwiftUI"]},
    "telegram":   {"files": ["**/*.py", "**/*.js", "**/*.ts"],
                   "signals": ["api.telegram.org", "setWebhook", "grammy", "telegraf", "python-telegram-bot", "aiogram", "telebot"]},
    "cloud":      {"files": ["Dockerfile", "docker-compose.yml", "*.tf", "serverless.yml", "wrangler.toml", "wrangler.jsonc", "**/k8s/**", "*.yaml"],
                   "signals": ["aws", "gcp", "azure", "cloudflare", "lambda", "kubernetes"]},
    "iot":        {"files": ["platformio.ini", "*.bin", "*.img", "**/firmware/**"],
                   "signals": ["mqtt", "esp32", "arduino", "freertos"]},
    "web3":       {"files": ["*.sol", "foundry.toml", "hardhat.config.js", "hardhat.config.ts", "truffle-config.js"],
                   "signals": ["solidity", "ethers", "web3", "pragma solidity"]},
    "llm":        {"files": ["**/*.py", "**/*.ts"],
                   "signals": ["openai", "anthropic", "langchain", "llamaindex", "prompt", "completion", "embedding"]},
    "vibe":       {"files": [".cursor", "CLAUDE.md", "AGENTS.md", ".cursorrules"],
                   "signals": ["cursor", "bolt", "lovable", "v0", "replit", "generated by ai"]},
    "browser-ext":{"files": ["manifest.json"],
                   "signals": ["chrome.runtime", "content_scripts", "manifest_version"]},
    "desktop":    {"files": ["electron", "**/main.js", "**/main.ts", "tauri.conf.json"],
                   "signals": ["electron", "BrowserWindow", "tauri"]},
    "generic":    {"files": ["**/.env", "**/package.json", "**/requirements.txt"], "signals": []},
}

def main():
    cards = load_cards()
    byid = {c["id"]: c for c in cards}
    profiles_dir = os.path.join(ROOT, "profiles")
    os.makedirs(profiles_dir, exist_ok=True)
    counts = {}
    for plat, fp in FINGERPRINTS.items():
        cand = [c for c in cards if plat in c["platforms"] or "generic" in c["platforms"]]
        cand.sort(key=lambda c: (-c["priority"], c["id"]))
        gate_fast = [c["id"] for c in cand][:25]
        gate_full = [c["id"] for c in cand]
        prof = {
            "name": plat,
            "description": f"Security launch gate for {plat} targets.",
            "platforms": [plat],
            "detect": fp,
            "gate": {"fast": gate_fast, "full": gate_full},
            "counts": {"fast": len(gate_fast), "full": len(gate_full)},
        }
        with open(os.path.join(profiles_dir, plat + ".yaml"), "w") as f:
            yaml.safe_dump(prof, f, sort_keys=False, allow_unicode=True, width=100)
        counts[plat] = len(gate_full)

    # playbooks
    pb = os.path.join(ROOT, "playbooks")
    os.makedirs(pb, exist_ok=True)
    def write_pb(name, desc, sel):
        ids = [c["id"] for c in sorted(sel, key=lambda c: (-c["priority"], c["id"]))]
        with open(os.path.join(pb, name + ".yaml"), "w") as f:
            yaml.safe_dump({"name": name, "description": desc, "checks": ids,
                            "count": len(ids)}, f, sort_keys=False, width=100)
    allcards = cards
    write_pb("quick-15", "Top 15 highest-priority checks for any codebase.",
             sorted(allcards, key=lambda c: -c["priority"])[:15])
    write_pb("pr-review", "Checks suitable for pull-request review.",
             [c for c in allcards if "pr-review" in c["phase"]])
    write_pb("pre-launch", "Pre-launch gate checks.", [c for c in allcards if "pre-launch" in c["phase"]])
    write_pb("full-audit", "Every check, full audit.", allcards)

    print("profiles:", json.dumps(counts))
    print("playbooks written: quick-15, pr-review, pre-launch, full-audit")

if __name__ == "__main__":
    main()
